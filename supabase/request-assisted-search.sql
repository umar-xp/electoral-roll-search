create or replace function public.public_create_search_request(
  applicant_name text,
  mobile text,
  email text default null,
  primary_voter_id text default null,
  secondary_voter_id text default null,
  old_voter_id text default null,
  has_old_voter_id boolean default false,
  knows_neighbor boolean default false,
  neighbor_found_in_2002 boolean default null,
  neighbor_name text default null,
  neighbor_locality text default null,
  neighbor_voter_id text default null,
  neighbor_ac_number text default null,
  neighbor_part_number text default null,
  neighbor_serial_number text default null,
  neighbor_found_screenshot_url text default null,
  declaration_accepted boolean default false,
  primary_front_url text default null,
  primary_back_url text default null,
  secondary_front_url text default null,
  secondary_back_url text default null,
  old_front_url text default null,
  old_back_url text default null,
  submission_key text default null
)
returns table (id bigint, order_id text, status text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_mobile text;
  v_record public.search_requests%rowtype;
begin
  v_mobile := regexp_replace(coalesce(mobile, ''), '\D', '', 'g');
  if applicant_name is null or trim(applicant_name) = '' then
    raise exception 'Applicant name is required';
  end if;
  if length(v_mobile) <> 10 then
    raise exception 'A valid 10-digit mobile number is required';
  end if;
  if primary_voter_id is null or trim(primary_voter_id) = '' then
    raise exception 'Primary voter ID is required';
  end if;
  if primary_front_url is null or trim(primary_front_url) = '' then
    raise exception 'Primary voter ID front image is required';
  end if;
  if primary_back_url is null or trim(primary_back_url) = '' then
    raise exception 'Primary voter ID back image is required';
  end if;
  if declaration_accepted is distinct from true then
    raise exception 'Declaration must be accepted';
  end if;

  insert into public.search_requests (
    applicant_name,
    mobile,
    email,
    primary_voter_id,
    secondary_voter_id,
    old_voter_id,
    has_old_voter_id,
    knows_neighbor,
    neighbor_found_in_2002,
    neighbor_name,
    neighbor_locality,
    neighbor_voter_id,
    neighbor_ac_number,
    neighbor_part_number,
    neighbor_serial_number,
    neighbor_found_screenshot_url,
    declaration_accepted,
    primary_front_url,
    primary_back_url,
    secondary_front_url,
    secondary_back_url,
    old_front_url,
    old_back_url,
    submission_key
  )
  values (
    trim(applicant_name),
    v_mobile,
    nullif(trim(email), ''),
    trim(primary_voter_id),
    nullif(trim(secondary_voter_id), ''),
    nullif(trim(old_voter_id), ''),
    coalesce(has_old_voter_id, false),
    coalesce(knows_neighbor, false),
    neighbor_found_in_2002,
    nullif(trim(neighbor_name), ''),
    nullif(trim(neighbor_locality), ''),
    nullif(trim(neighbor_voter_id), ''),
    nullif(trim(neighbor_ac_number), ''),
    nullif(trim(neighbor_part_number), ''),
    nullif(trim(neighbor_serial_number), ''),
    nullif(trim(neighbor_found_screenshot_url), ''),
    true,
    trim(primary_front_url),
    trim(primary_back_url),
    nullif(trim(secondary_front_url), ''),
    nullif(trim(secondary_back_url), ''),
    nullif(trim(old_front_url), ''),
    nullif(trim(old_back_url), ''),
    coalesce(nullif(submission_key, '')::uuid, gen_random_uuid())
  )
  returning * into v_record;

  return query select v_record.id, v_record.order_id, v_record.status;
end;
$$;

