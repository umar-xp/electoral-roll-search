-- Request Assisted Search schema for the Karnataka 2002 voter search website.
-- Apply in the Supabase SQL editor after creating your project.
-- This version is designed for the existing static site and public form flow.

create extension if not exists pgcrypto;

create table if not exists public.search_requests (
  id bigint generated by default as identity primary key,
  order_id text unique,
  created_at timestamptz not null default now(),
  applicant_name text not null,
  mobile text not null,
  email text,
  primary_voter_id text not null,
  secondary_voter_id text,
  old_voter_id text,
  has_old_voter_id boolean not null default false,
  knows_neighbor boolean not null default false,
  neighbor_found_in_2002 boolean,
  neighbor_name text,
  neighbor_locality text,
  neighbor_voter_id text,
  neighbor_ac_number text,
  neighbor_part_number text,
  neighbor_serial_number text,
  neighbor_found_screenshot_url text,
  declaration_accepted boolean not null default false,
  primary_front_url text not null,
  primary_back_url text not null,
  secondary_front_url text,
  secondary_back_url text,
  old_front_url text,
  old_back_url text,
  status text not null default 'NEW',
  assigned_volunteer text,
  assigned_date timestamptz,
  ac_number text,
  part_number text,
  serial_number text,
  result_status text,
  remarks text,
  completed_at timestamptz,
  submission_key uuid not null default gen_random_uuid(),
  constraint search_requests_status_check check (status in ('NEW', 'ASSIGNED', 'COMPLETED', 'NOT_FOUND')),
  constraint search_requests_result_status_check check (result_status is null or result_status in ('FOUND', 'NOT_FOUND')),
  constraint search_requests_mobile_check check (mobile ~ '^[0-9]{10}$')
);

create unique index if not exists search_requests_submission_key_idx on public.search_requests (submission_key);
create index if not exists search_requests_order_id_idx on public.search_requests (order_id);
create index if not exists search_requests_mobile_idx on public.search_requests (mobile);
create index if not exists search_requests_status_idx on public.search_requests (status);
create index if not exists search_requests_assigned_volunteer_idx on public.search_requests (assigned_volunteer);

