create sequence if not exists public.search_request_order_seq start 1;

create or replace function public.generate_search_request_order_id()
returns trigger
language plpgsql
as $$
begin
  if new.order_id is null or trim(new.order_id) = '' then
    new.order_id := 'VSR-' || lpad(nextval('public.search_request_order_seq')::text, 6, '0');
  end if;
  return new;
end;
$$;

drop trigger if exists trg_generate_search_request_order_id on public.search_requests;
create trigger trg_generate_search_request_order_id
before insert on public.search_requests
for each row
execute function public.generate_search_request_order_id();

create table if not exists public.request_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create or replace function public.is_request_admin(uid uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.request_admins
    where user_id = uid
      and is_active = true
  );
$$;

revoke all on public.search_requests from anon, authenticated;
